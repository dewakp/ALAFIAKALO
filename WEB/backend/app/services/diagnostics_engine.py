    async def assess_symptoms(
        self,
        user: User,
        symptoms: List[Dict[str, Any]],
        additional_context: Optional[str] = None,
    ) -> Dict[str, Any]:
        """Run a full diagnostic assessment from reported symptoms.

        Args:
            user: The patient
            symptoms: List of dicts with keys:
                - name (str): symptom name
                - severity (int 1-10): optional severity
                - duration (str): optional duration e.g. "3 days"
                - body_part (str): optional location
                - quality (str): optional e.g. "sharp", "dull"
                - pattern (str): optional e.g. "constant", "intermittent"
            additional_context: Free-text additional info from patient

        Returns:
            Structured diagnostic assessment dict.
        """
        # 1. Gather all patient context
        patient_context = await self._gather_patient_context(user)

        # 2. Rule-based initial screening
        symptom_names = [s["name"] for s in symptoms]
        urgency = self._assess_urgency(symptom_names)
        icd_matches = get_codes_by_symptoms(symptom_names, min_match=1)

        # 3. Build rule-based differential
        rule_based_differential = self._build_rule_based_differential(
            symptoms, icd_matches, patient_context
        )

        # 4. LLM-powered deep analysis
        llm_assessment = await self._llm_diagnostic_reasoning(
            symptoms, patient_context, rule_based_differential, additional_context
        )

        # 5. Compose final assessment
        assessment = {
            "assessment_id": f"DX-{datetime.now(timezone.utc).strftime('%Y%m%d%H%M%S')}-{user.id}",
            "patient_id": user.id,
            "assessed_at": datetime.now(timezone.utc).isoformat(),
            "urgency": urgency,
            "reported_symptoms": symptoms,
            "differential_diagnoses": llm_assessment.get("differentials", rule_based_differential[:10]),
            "primary_impression": llm_assessment.get("primary_impression", "Assessment requires further evaluation"),
            "supporting_evidence": llm_assessment.get("supporting_evidence", []),
            "contradicting_factors": llm_assessment.get("contradicting_factors", []),
            "recommended_actions": llm_assessment.get("recommended_actions", []),
            "recommended_tests": llm_assessment.get("recommended_tests", []),
            "red_flags": llm_assessment.get("red_flags", []),
            "risk_factors_identified": llm_assessment.get("risk_factors", []),
            "follow_up_timeline": llm_assessment.get("follow_up_timeline", "As advised by healthcare provider"),
            "patient_education": llm_assessment.get("patient_education", []),
            "disclaimer": self.DISCLAIMER,
        }

        return assessment

    async def proactive_screening(self, user: User) -> Dict[str, Any]:
        """Analyze patient's complete profile for proactive health screening.

        Reviews demographics, family history, lifestyle, vitals, labs,
        and existing conditions to identify:
         - Overdue screenings
         - Elevated risk conditions
         - Emerging patterns
         - Preventive recommendations
        """
        patient_context = await self._gather_patient_context(user)
        recommendations = self._rule_based_screening(patient_context)

        # Enhance with LLM analysis
        llm_screening = await self._llm_proactive_screening(patient_context)

        return {
            "screening_id": f"SCR-{datetime.now(timezone.utc).strftime('%Y%m%d%H%M%S')}-{user.id}",
            "patient_id": user.id,
            "screened_at": datetime.now(timezone.utc).isoformat(),
            "risk_profile": llm_screening.get("risk_profile", recommendations.get("risk_profile", {})),
            "recommended_screenings": llm_screening.get("recommended_screenings", recommendations.get("screenings", [])),
            "emerging_patterns": llm_screening.get("emerging_patterns", []),
            "preventive_actions": llm_screening.get("preventive_actions", recommendations.get("preventive", [])),
            "lifestyle_modifications": llm_screening.get("lifestyle_modifications", []),
            "disclaimer": self.DISCLAIMER,
        }

    async def correlate_lab_results(
        self,
        user: User,
        lab_result_ids: Optional[List[int]] = None,
    ) -> Dict[str, Any]:
        """Correlate lab results with symptoms and conditions for diagnostic insights."""
        patient_context = await self._gather_patient_context(user)

        # Get specific lab results or recent ones
        if lab_result_ids:
            stmt = select(LabResult).where(
                and_(LabResult.user_id == user.id, LabResult.id.in_(lab_result_ids))
            )
        else:
            stmt = (
                select(LabResult)
                .where(LabResult.user_id == user.id)
                .order_by(desc(LabResult.test_date))
                .limit(20)
            )
        result = await self.db.execute(stmt)
        labs = result.scalars().all()

        lab_data = [
            {
                "test_name": lab.test_name,
                "value": lab.value,
                "unit": lab.unit,
                "reference_range": f"{lab.reference_range_low}-{lab.reference_range_high}" if lab.reference_range_low else None,
                "is_abnormal": lab.is_abnormal,
                "test_date": str(lab.test_date) if lab.test_date else None,
                "loinc_code": lab.loinc_code,
            }
            for lab in labs
        ]

        abnormal_labs = [l for l in lab_data if l.get("is_abnormal")]

        # LLM correlation analysis
        correlation = await self._llm_lab_correlation(
            lab_data, abnormal_labs, patient_context
        )

        return {
            "correlation_id": f"LAB-{datetime.now(timezone.utc).strftime('%Y%m%d%H%M%S')}-{user.id}",
            "patient_id": user.id,
            "analyzed_at": datetime.now(timezone.utc).isoformat(),
            "labs_analyzed": len(lab_data),
            "abnormal_count": len(abnormal_labs),
            "abnormal_labs": abnormal_labs,
            "diagnostic_correlations": correlation.get("correlations", []),
            "possible_conditions": correlation.get("possible_conditions", []),
            "recommended_follow_up_tests": correlation.get("follow_up_tests", []),
            "clinical_significance": correlation.get("clinical_significance", "Requires professional interpretation"),
            "disclaimer": self.DISCLAIMER,
        }

