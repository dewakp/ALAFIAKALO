    async def _gather_patient_context(self, user: User) -> Dict[str, Any]:
        """Build comprehensive patient context from all data sources."""
        cutoff = datetime.now(timezone.utc) - timedelta(days=90)

        # Parallel queries
        conditions_stmt = select(HealthCondition).where(
            and_(HealthCondition.user_id == user.id, HealthCondition.status.in_(["active", "managed"]))
        )
        chronic_stmt = select(ChronicCondition).where(
            and_(ChronicCondition.user_id == user.id, ChronicCondition.is_active == True)
        )
        symptoms_stmt = (
            select(SymptomLog)
            .where(and_(SymptomLog.user_id == user.id, SymptomLog.created_at >= cutoff))
            .order_by(desc(SymptomLog.created_at))
            .limit(20)
        )
        meds_stmt = select(Medication).where(
            and_(Medication.user_id == user.id, Medication.is_active == True)
        )
        vitals_stmt = (
            select(VitalsLog)
            .where(VitalsLog.user_id == user.id)
            .order_by(desc(VitalsLog.created_at))
            .limit(5)
        )
        labs_stmt = (
            select(LabResult)
            .where(and_(LabResult.user_id == user.id, LabResult.test_date >= cutoff.date()))
            .order_by(desc(LabResult.test_date))
            .limit(20)
        )
        illness_stmt = (
            select(IllnessLog)
            .where(and_(IllnessLog.user_id == user.id, IllnessLog.created_at >= cutoff))
            .order_by(desc(IllnessLog.created_at))
            .limit(10)
        )

        conditions_r = await self.db.execute(conditions_stmt)
        chronic_r = await self.db.execute(chronic_stmt)
        symptoms_r = await self.db.execute(symptoms_stmt)
        meds_r = await self.db.execute(meds_stmt)
        vitals_r = await self.db.execute(vitals_stmt)
        labs_r = await self.db.execute(labs_stmt)
        illness_r = await self.db.execute(illness_stmt)

        conditions = conditions_r.scalars().all()
        chronic = chronic_r.scalars().all()
